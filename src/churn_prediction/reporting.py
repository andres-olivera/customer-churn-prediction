"""Reproducible exploratory charts and locked-test model diagnostics."""
from pathlib import Path

import joblib
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from sklearn.inspection import permutation_importance
from sklearn.metrics import (
    ConfusionMatrixDisplay, PrecisionRecallDisplay, RocCurveDisplay,
)
from sklearn.model_selection import train_test_split

from .data import FEATURES, TARGET, load_data
from .modeling import SEED


def generate_figures(
    csv_path, artifact_path="artifacts/churn_model.joblib",
    output_dir="reports/figures",
):
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    frame = load_data(csv_path)
    y = frame[TARGET].astype(int)
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.bar(["Retained", "Churned"], y.value_counts().reindex([0, 1], fill_value=0))
    ax.set(title="Customer churn distribution", ylabel="Customers")
    fig.tight_layout()
    fig.savefig(output / "target_distribution.png", dpi=160)
    plt.close(fig)

    # EXACT same held-out rows as in training, obtained deterministically from seed.
    _, X_test, _, y_test = train_test_split(
        frame[FEATURES], y, test_size=0.2, stratify=y, random_state=SEED,
    )
    # Load only joblib artifacts generated by this trusted source code.
    artifact = joblib.load(artifact_path)
    if artifact["features"] != FEATURES:
        raise ValueError("Artifact features mismatch the source contract")
    model = artifact["model"]
    probability = model.predict_proba(X_test)[:, 1]
    threshold = artifact["threshold"]

    fig, ax = plt.subplots(figsize=(6, 5))
    PrecisionRecallDisplay.from_predictions(y_test, probability, ax=ax)
    fig.tight_layout()
    fig.savefig(output / "precision_recall.png", dpi=160)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(6, 5))
    RocCurveDisplay.from_predictions(y_test, probability, ax=ax)
    fig.tight_layout()
    fig.savefig(output / "roc_curve.png", dpi=160)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(6, 5))
    ConfusionMatrixDisplay.from_predictions(
        y_test, probability >= threshold, ax=ax, colorbar=False,
    )
    fig.tight_layout()
    fig.savefig(output / "confusion_matrix.png", dpi=160)
    plt.close(fig)

    # Descriptive importance on locked test set, NEVER used to select/tune a model.
    importance = permutation_importance(
        model, X_test, y_test, n_repeats=5,
        random_state=SEED, scoring="average_precision", n_jobs=1,
    )
    order = np.argsort(importance.importances_mean)
    fig, ax = plt.subplots(figsize=(9, 6))
    ax.barh(np.array(FEATURES)[order], importance.importances_mean[order])
    ax.set(
        xlabel="Mean decrease in average precision after permutation",
        title="Permutation feature importance (test set)",
    )
    fig.tight_layout()
    fig.savefig(output / "permutation_importance.png", dpi=160)
    plt.close(fig)
